# ----------------------------------------------------------------- áp vào kịch bản
def apply(s):
    """Gắn `subtitles` vào từng chặng của kịch bản s (bỏ qua kịch bản đã có phụ đề, ví dụ Khủng long)."""
    rows = SUBS.get(s['id'])
    if rows is None:
        return
    assert len(rows) == len(s['stages']), (s['id'], len(rows), len(s['stages']))
    for st, lines in zip(s['stages'], rows):
        assert lines, (s['id'], st['n'])
        st['subtitles'] = lines
